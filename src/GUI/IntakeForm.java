    public String errorHandling() {
    String error = "";
    
    // Pet Name
    String petName = nameTextField.getText().trim();
    if (petName.isEmpty()) {
        error += "- Name cannot be empty.\n";
    } else if (!petName.matches("[a-zA-Z\\s]+")) {
        error += "- Name should only contain letters and spaces.\n";
    } else if (petName.length() > 30) {
        error += "- Name cannot be longer than 30 characters.\n";
    }
    
    // Breed
    String breed = breedTextField.getText().trim();
    if (breed.isEmpty()) {
        error += "- Breed cannot be empty.\n";
    } else if (!breed.matches("[a-zA-Z\\s]+")) {
        error += "- Breed should only contain letters and spaces.\n";
    } else if (breed.length() > 50) {
        error += "- Breed cannot be longer than 50 characters.\n";
    }
    
    // Intake Date
    LocalDate intakeDate = intakedatePicker.getDate();
    if (intakeDate == null) {
        error += "- Intake date cannot be empty.\n";
    } else {
        LocalDate today = LocalDate.now();
        if (intakeDate.isAfter(today)) {
            error += "- Intake date cannot be in the future.\n";
        }
    }
    
    // Animal Type
    if (!dogRadioButton.isSelected() && !catRadioButton.isSelected()) {
        error += "- Please select an Animal Type (Dog or Cat).\n";
    }
    
    // Age
    int years = (int) yearsSpinner.getValue();
    int months = (int) monthsSpinner.getValue();
    int totalMonths = (years * 12) + months;
    if (totalMonths == 0) {
        error += "- Age cannot be 0 years and 0 months.\n";
    }
    
    // Energy Level (only required for Dogs)
    if (dogRadioButton.isSelected()) {
        String energy = (String) energyComboBox.getSelectedItem();
        if (energy == null || energy.trim().isEmpty() || energy.trim().equals(" ")) {
            error += "- Please select an Energy Level (High/Medium/Low).\n";
        }
    }
    
    // Adoption Fee
    try {
        double fee = Double.parseDouble(adoptionFeeTextField.getText());
        if (fee < 0) {
            error += "- Adoption fee cannot be negative.\n";
        }
    } catch (NumberFormatException e) {
        error += "- Please enter a valid number for the adoption fee (e.g. 875.50).\n";
    }
    
    return error;
}
