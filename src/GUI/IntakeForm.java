    private void registerButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_registerButtonActionPerformed
        // TODO add your handling code here:
        String errorMsg = errorHandling();
    
    if (errorMsg.isEmpty()) {
        int years = (int) yearsSpinner.getValue();
        int months = (int) monthsSpinner.getValue();
        int totalMonths = (years * 12) + months;
    
        String petName = nameTextField.getText().trim();
        String breed = breedTextField.getText().trim();
        LocalDate intakeDate = intakedatePicker.getDate();
        
        String animalType = dogRadioButton.isSelected() ? "Dog" : "Cat";
        
        String energy = (String) energyComboBox.getSelectedItem();
        if (energy != null) {
            energy = energy.trim();
        }
        
        Boolean isChildFriendly = "Yes".equals(childFriendlyComboBox.getSelectedItem());
        Boolean isIndoor = "Yes".equals(indoorComboBox.getSelectedItem());
        
        double fee = Double.parseDouble(adoptionFeeTextField.getText());

        String petID = dbManager.generateNextPetID();
        
        boolean success = dbManager.insertPet(petID, petName, totalMonths, breed,intakeDate, animalType, energy,isIndoor, isChildFriendly, fee);
        
        if (success) {
            JOptionPane.showMessageDialog(this, "Successfully registered " + petName + "!");
            clearFields();
        } else {
            JOptionPane.showMessageDialog(this, "Failed to save pet to database.","Database Error", JOptionPane.ERROR_MESSAGE);
        }
        
    } else {
        JOptionPane.showMessageDialog(this, errorMsg, "Input Errors", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_registerButtonActionPerformed

