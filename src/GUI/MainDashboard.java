    private void catsButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_catsButtonActionPerformed
        // TODO add your handling code here:
        //Only shows the available pets that are cats
        catsFilterActive = !catsFilterActive;
        dogsFilterActive = false;
 
        if (catsFilterActive) {
            ArrayList<Pet> catsOnly = new ArrayList<>();
            for (Pet p : allPets) {
                if ("Cat".equalsIgnoreCase(p.getType())) {
                    catsOnly.add(p);
                }
            }
            populateTable(catsOnly);
            updateLongStayLabel(catsOnly);
        } else {
            populateTable(allPets);
            updateLongStayLabel(allPets);
        }
    }//GEN-LAST:event_catsButtonActionPerformed

