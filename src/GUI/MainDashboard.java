    /**
     * Pulls the current (non-adopted) pets from the database and displays
     * them, then updates the long-stay alert label.
     */
    private void loadDashboard() {
        allPets = dbManager.getAllPets();
        populateTable(allPets);
        updateLongStayLabel(allPets);
    }//loadDashboard
    
     // Fills petTable with the given list of pets.
    private void populateTable(ArrayList<Pet> petsToShow) {
        DefaultTableModel model = (DefaultTableModel) petTable.getModel();
        model.setRowCount(0);
        for (Pet p : petsToShow) {
            model.addRow(new Object[]{
                p.getPetName(),
                p.getType(),
                p.getAgeMonths(),
                p.getAdoptionFee(),
                p.calculateDateInShelter()
            });
        }
    }//populateTable
 
    // Updates the "Long Stay Alert" label with how many current pets have been in the shelter for more than 30 days
    private void updateLongStayLabel(ArrayList<Pet> petsToCheck) {
        long longStayCount = petsToCheck.stream().filter(p -> p.calculateDateInShelter() > 30).count();
        longStayLabel.setText("Long Stay Alert: " + longStayCount
                + " animal(s) over 30 days in shelter");
    }//updateLongStayLabel
 
    // Highlights rows where "Days In Shelter" exceeds 30 days
    private class LongStayRowRenderer extends DefaultTableCellRenderer {
        @Override
        public Component getTableCellRendererComponent(JTable table, Object value,
                boolean isSelected, boolean hasFocus, int row, int column) {
            Component c = super.getTableCellRendererComponent(table, value, isSelected, hasFocus, row, column);
 
            Object daysValue = table.getModel().getValueAt(row, 4);
            boolean isLongStay = (daysValue instanceof Integer) && ((Integer) daysValue) > 30;
 
            if (!isSelected) {
                c.setBackground(isLongStay ? new Color(255, 205, 205) : Color.WHITE);
            }
            return c;
        }
    }//LongStayRowRenderer

